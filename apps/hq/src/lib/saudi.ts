/** Strings with numbers or names inside. */
export const SA_RX: [RegExp, string][] = [
  [/^استخدمت (\S+) من (\S+) جولات تعديل متضمنة\. الجولات الإضافية ممكن يتعملها عرض سعر منفصل\.$/, "استخدمت $1 من $2 جولات تعديل ضمن الاتفاق. الجولات الزيادة ممكن يكون لها عرض سعر منفصل."],
  [/^(\d+) ملاحظة على الصورة\. فيه حاجة تانية؟$/, "$1 ملاحظة على الصورة. فيه شي ثاني؟"],
  [/^أهلًا (.+)$/, "هلا $1"],
  [/^فيه (\d+) حاجة محتاجة موافقتك\. اضغط على أي حاجة تراجعها، أو اختار كذا حاجة ووافق عليهم مرة واحدة\.$/, "فيه $1 أشياء تحتاج موافقتك. اضغط على أي شي عشان تراجعه، أو اختر أكثر من شي ووافق عليها مرة وحدة."],
  [/^(\d+) متختارين$/, "$1 مختارة"]
];

export function toSaudi(ar: string): string {
  if (SA[ar]) return SA[ar];
  for (const [re, to] of SA_RX) if (re.test(ar)) return ar.replace(re, to);
  return ar;
}
